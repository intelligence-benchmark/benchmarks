"""Generated JSON Schema and TypeScript types from the Pydantic models (P0-S5-T01; 04 S12, 05 S3).

    bench schema gen            # write schema/generated/*.schema.json and site/src/types/*.d.ts
    bench schema gen --check    # regenerate in memory; exit 1 if anything on disk differs

04 S12's pipeline:

    taxonomy/*.yaml --loaded at import time--> dynamic Literal enums
    schema/*.py            model_json_schema()  -> JSON Schema Draft 2020-12   schema/generated/
                           json-schema-to-typescript@16.0.0                    site/src/types/

Pydantic is canonical; both artifacts are committed, and "CI fails if regeneration produces a diff".
Because the vocabularies are Literal enums built from taxonomy/ at import time, a taxonomy edit
changes the output too, so `--check` catches drift from either source (05 S3's `schema gen` row).

One schema and one type file per entity: every root model schema/paths.py registers. The JSON Schema
is the VALIDATION schema -- what a hand-written or ingested record may contain -- so derived,
computed fields (`execution.inspect_evals_available`, `Metric.higher_is_better`) are not in it.

Determinism: models are walked in name order, JSON is written with a fixed indent and a trailing
newline, and every file is written LF (the repository's .gitattributes pins eol=lf). The TypeScript
step runs json-schema-to-typescript's own `compile` from site/node_modules, pinned in
site/package.json, in one node process.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DRAFT = 'https://json-schema.org/draft/2020-12/schema'
BANNER = ('/* Generated by `bench schema gen` from schema/*.py and taxonomy/*.yaml (P0-S5-T01).\n'
          ' * Do not edit: change the Pydantic model or the vocabulary and regenerate. */')
JSON_DIR = os.path.join('schema', 'generated')
TS_DIR = os.path.join('site', 'src', 'types')
JSON2TS = os.path.join('site', 'node_modules', 'json-schema-to-typescript')

_NODE = r"""
const {compile} = require(process.argv[1]);
let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', d => { input += d; });
process.stdin.on('end', async () => {
  const schemas = JSON.parse(input), out = {};
  for (const name of Object.keys(schemas).sort()) {
    out[name] = await compile(schemas[name], name, {
      bannerComment: process.argv[2], unknownAny: true, format: true, additionalProperties: false,
    });
  }
  process.stdout.write(JSON.stringify(out));
});
"""


def slug(name: str) -> str:
    """ResultClaim -> result-claim."""
    return re.sub(r'(?<!^)(?=[A-Z])', '-', name).lower()


def json_schemas(root: str = ROOT) -> dict[str, dict]:
    if root not in sys.path:
        sys.path.insert(0, root)
    from schema.paths import ENTITIES
    out = {}
    for name in sorted(ENTITIES):
        body = ENTITIES[name].model_json_schema(mode='validation')
        out[name] = {'$schema': DRAFT,
                     '$comment': 'Generated by `bench schema gen` from schema/*.py and taxonomy/*.yaml. Do not edit.',
                     **body}
    return out


def _untitled_properties(node):
    """A copy with the `title` Pydantic puts on every property removed. json-schema-to-typescript turns
    each titled sub-schema into its own named alias (`export type Id = string`); without the titles a
    property's type is written inline. Model titles, which name the interfaces, are kept. Only the
    TypeScript input is changed: the committed JSON Schema is exactly what Pydantic emits."""
    if isinstance(node, list):
        return [_untitled_properties(x) for x in node]
    if not isinstance(node, dict):
        return node
    out = {k: _untitled_properties(v) for k, v in node.items()}
    if isinstance(out.get('properties'), dict):
        out['properties'] = {k: {kk: vv for kk, vv in v.items() if kk != 'title'} if isinstance(v, dict) else v
                             for k, v in out['properties'].items()}
    return out


def typescript(schemas: dict[str, dict], json2ts: str) -> dict[str, str]:
    node = shutil.which('node')
    if node is None:
        raise RuntimeError('node is not on PATH; the TypeScript step needs it (08 S5.1 pins node >= 22.12)')
    index = os.path.join(json2ts, 'dist', 'src', 'index.js')
    if not os.path.exists(index):
        raise RuntimeError('%s not found: run `npm ci` in site/ (json-schema-to-typescript@16.0.0)' % index)
    r = subprocess.run([node, '-e', _NODE, index, BANNER], input=json.dumps(_untitled_properties(schemas)),
                       capture_output=True, text=True, encoding='utf-8', check=False)
    if r.returncode != 0:
        raise RuntimeError('json-schema-to-typescript failed:\n' + r.stderr)
    return {name: ts.replace('\r\n', '\n') for name, ts in json.loads(r.stdout).items()}


def render(root: str = ROOT, json2ts: str | None = None) -> dict[str, str]:
    """Every generated file, repo-relative path -> content."""
    schemas = json_schemas(root)
    files = {os.path.join(JSON_DIR, slug(n) + '.schema.json').replace(os.sep, '/'):
             json.dumps(s, indent=2, ensure_ascii=False) + '\n' for n, s in schemas.items()}
    for n, ts in typescript(schemas, json2ts or os.path.join(root, JSON2TS)).items():
        files[os.path.join(TS_DIR, slug(n) + '.d.ts').replace(os.sep, '/')] = ts
    return files


def _on_disk(root: str) -> set[str]:
    found = set()
    for d, suffix in ((JSON_DIR, '.schema.json'), (TS_DIR, '.d.ts')):
        full = os.path.join(root, d)
        if os.path.isdir(full):
            found |= {(d + '/' + f).replace(os.sep, '/') for f in os.listdir(full) if f.endswith(suffix)}
    return found


def drift(root: str = ROOT, json2ts: str | None = None) -> list[str]:
    """What `--check` reports: files that differ, are missing, or are generated by nothing."""
    want = render(root, json2ts)
    problems = []
    for rel, content in sorted(want.items()):
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            problems.append('missing  %s' % rel)
        elif open(path, encoding='utf-8', newline='').read() != content:
            problems.append('differs  %s' % rel)
    problems += ['stale    %s' % rel for rel in sorted(_on_disk(root) - set(want))]
    return problems


def write(root: str = ROOT, json2ts: str | None = None) -> list[str]:
    want = render(root, json2ts)
    for rel in sorted(_on_disk(root) - set(want)):
        os.remove(os.path.join(root, rel))
    changed = []
    for rel, content in sorted(want.items()):
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        old = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
        if old != content:
            with open(path, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(content)
            changed.append(rel)
    return changed
