#!/usr/bin/env python3
"""Entries merged per week, counted from git history, and 14-roadmap.md's stopping rule (c).

14-roadmap.md "Phase risk" (Phase 1): "track entries per week publicly in the repo, pull the Tier-2
lighter-stub lever on the stated trigger ... rather than on a feeling". Stopping rule (c): "entries
per week below five for four consecutive weeks".

    python scripts/throughput_report.py                    # write docs/curation-throughput.md
    python scripts/throughput_report.py --check            # exit 1 when rule (c) fires
    python scripts/throughput_report.py --as-of 2026-11-02 --repo path/to/clone

What is counted. An entry is a file data/benchmarks/<family>/<id>.yaml (05 S5 naming; a name
starting with `_` is not an entry). It is counted once, in the ISO week (Monday to Sunday, UTC) of
the committer date of the first commit on main's first-parent line that adds it -- the moment it
was merged, whether by a merge commit, a squash or a direct push. A rename is not a new entry and a
file deleted and re-added counts once. The curation-timing ledger (metrics/curation-rate.jsonl) is
deliberately not used: it records effort, and this records output.

The rule. Weeks are counted from the week of the first entry, because rule (c) is about curation
that has started. The four weeks examined are the last four COMPLETE weeks before the week of
--as-of (default: today, UTC); the current week is partial and never counted against anyone. Rule
(c) fires when each of those four weeks holds fewer than five entries -- "below five for four
consecutive weeks". The four-week mean is printed beside it: P1-S2-T07's own wording ("the trailing
four-week rate is below five per week") would read 0, 0, 0, 12 as firing, and the roadmap's rule
would not. Fewer than four complete weeks of history is reported as such and never fires.

Output is deterministic for a given history and --as-of: rendering twice is byte-identical.
"""
import argparse
import os
import re
import subprocess
import sys
from datetime import date, datetime, timedelta, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE = os.path.join(ROOT, 'docs', 'curation-throughput.md')
ENTRY = re.compile(r'^data/benchmarks/[^/]+/[^_/][^/]*\.yaml$')
THRESHOLD = 5  # entries per week, 14-roadmap.md Stopping rules (c)
WINDOW = 4     # consecutive weeks


def merged_entries(repo):
    """{path: first-parent committer datetime (UTC) of the commit that first added it}."""
    out = subprocess.run(
        ['git', '-C', repo, 'log', '--first-parent', '--diff-merges=first-parent', '--reverse', '-M',
         '--diff-filter=A', '--name-only', '--format=%x00%cI', '--', 'data/benchmarks'],
        check=True, capture_output=True, text=True, encoding='utf-8').stdout
    first = {}
    for block in out.split('\x00')[1:]:
        lines = [l for l in block.splitlines() if l.strip()]
        when = datetime.fromisoformat(lines[0]).astimezone(timezone.utc)
        for path in lines[1:]:
            if ENTRY.match(path) and path not in first:
                first[path] = when
    return first


def monday(d):
    return d - timedelta(days=d.weekday())


def weekly(first, as_of):
    """[(week_monday, count)] from the first entry's week through the week of as_of."""
    if not first:
        return []
    counts = {}
    for when in first.values():
        wk = monday(when.date())
        if wk <= monday(as_of):
            counts[wk] = counts.get(wk, 0) + 1
    if not counts:
        return []
    weeks, wk = [], min(counts)
    while wk <= monday(as_of):
        weeks.append((wk, counts.get(wk, 0)))
        wk += timedelta(days=7)
    return weeks


def verdict(weeks, as_of):
    """(state, window) with state 'fires' | 'ok' | 'insufficient' | 'empty'."""
    complete = [w for w in weeks if w[0] < monday(as_of)]
    if not weeks:
        return 'empty', []
    if len(complete) < WINDOW:
        return 'insufficient', complete
    window = complete[-WINDOW:]
    return ('fires' if all(n < THRESHOLD for _, n in window) else 'ok'), window


def render(weeks, as_of, state, window):
    iso = lambda d: '%d-W%02d' % d.isocalendar()[:2]  # noqa: E731
    lines = [
        '# Curation throughput',
        '',
        '<!-- Generated by scripts/throughput_report.py; do not edit by hand. -->',
        '',
        'Benchmark entries merged per week, counted from git history: each file',
        '`data/benchmarks/<family>/<id>.yaml` in the ISO week its first commit landed on `main`.',
        'Stopping rule (c) of the roadmap fires when **each of the last %d complete weeks holds fewer' % WINDOW,
        'than %d entries**; the response is to switch the ingest-then-verify families to Tier-2 stub' % THRESHOLD,
        'mode and publish that decision on the methodology page.',
        '',
        '**As of %s** (%s, the current week, is partial and not judged).' % (as_of.isoformat(), iso(as_of)),
        '',
    ]
    total = sum(n for _, n in weeks)
    if state == 'empty':
        lines += ['No entries have been merged yet.', '']
    else:
        if state == 'insufficient':
            lines.append('**Rule (c): not yet assessable** -- %d complete week(s) of curation, %d needed.'
                         % (len(window), WINDOW))
        else:
            mean = sum(n for _, n in window) / WINDOW
            lines.append('**Rule (c): %s.** Last %d complete weeks: %s (mean %.2f a week).' % (
                'FIRES' if state == 'fires' else 'does not fire', WINDOW,
                ', '.join('%s %d' % (iso(w), n) for w, n in window), mean))
        lines += ['', '%d entries merged in total.' % total, '',
                  '| Week | Starts | Entries | Cumulative |', '| --- | --- | ---: | ---: |']
        run = 0
        for wk, n in weeks:
            run += n
            lines.append('| %s | %s | %d | %d |' % (iso(wk), wk.isoformat(), n, run))
        lines.append('')
    return '\n'.join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--repo', default=ROOT)
    p.add_argument('--as-of', type=date.fromisoformat, default=None, help='YYYY-MM-DD, default today (UTC)')
    p.add_argument('--out', default=PAGE, help='page to write (not written with --check)')
    p.add_argument('--check', action='store_true', help='exit 1 when stopping rule (c) fires')
    a = p.parse_args(argv)
    as_of = a.as_of or datetime.now(timezone.utc).date()

    weeks = weekly(merged_entries(a.repo), as_of)
    state, window = verdict(weeks, as_of)
    if a.check:
        if state == 'fires':
            print('STOPPING RULE (c) fires: fewer than %d entries in each of the last %d complete weeks '
                  '(%s). Switch the ingest-then-verify families to Tier-2 stub mode and publish the '
                  'decision (14-roadmap.md Stopping rules).' % (
                      THRESHOLD, WINDOW, ', '.join('%s: %d' % (w.isoformat(), n) for w, n in window)))
            return 1
        print('stopping rule (c): %s' % {'ok': 'does not fire', 'insufficient': 'not yet assessable, %d of '
              '%d complete weeks' % (len(window), WINDOW), 'empty': 'no entries yet'}[state])
        return 0
    page = render(weeks, as_of, state, window)
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(page)
    print('wrote %s (%s)' % (a.out, state))
    return 0


if __name__ == '__main__':
    sys.exit(main())
